# ==============================================================================
# Secure TiDB Cloud Setup & Connection Verifier
# Configures .env locally, verifies schema, imports data safely, and tests live connection.
# ==============================================================================

[CmdletBinding()]
param()

$ProjectRoot = (Get-Item -Path "$PSScriptRoot\..").FullName
$EnvFilePath = Join-Path $ProjectRoot ".env"
$BackupFilePath = Join-Path $ProjectRoot "database\campus_club_backup.sql"
$JarPath = Join-Path $ProjectRoot "target\campus-club-management-system-1.0.0.jar"
$MySqlExe = "C:\Program Files\MySQL\MySQL Server 8.4\bin\mysql.exe"

if (-not (Test-Path $MySqlExe)) {
    $cmd = Get-Command mysql -ErrorAction SilentlyContinue
    if ($cmd) { $MySqlExe = $cmd.Source }
}

Write-Host "============================================================" -ForegroundColor Cyan
Write-Host "  Campus Club Management System - TiDB Cloud Setup" -ForegroundColor Cyan
Write-Host "============================================================" -ForegroundColor Cyan
Write-Host "Target Project : $ProjectRoot"
Write-Host "Security Policy: Credentials will be saved directly into git-ignored .env file."
Write-Host "                 Passwords are typed privately with masking and never shared.`n"

# 1. Prompt for connection parameters securely
$HostInput = Read-Host "Enter TiDB Host (e.g. gateway01.us-east-1.prod.aws.tidbcloud.com)"
if ([string]::IsNullOrWhiteSpace($HostInput)) {
    Write-Host "Error: TiDB Host is required." -ForegroundColor Red
    exit 1
}

$PortInput = Read-Host "Enter Port [Press Enter for default: 4000]"
if ([string]::IsNullOrWhiteSpace($PortInput)) { $PortInput = "4000" }

$UserInput = Read-Host "Enter TiDB User (e.g. 4Xyz123Abc.root)"
if ([string]::IsNullOrWhiteSpace($UserInput)) {
    Write-Host "Error: TiDB User is required." -ForegroundColor Red
    exit 1
}

$DbName = Read-Host "Enter Database Name [Press Enter for default: campus_club_db]"
if ([string]::IsNullOrWhiteSpace($DbName)) { $DbName = "campus_club_db" }

# Read password as SecureString so it is masked as ****** on screen
$SecurePass = Read-Host "Enter TiDB Password" -AsSecureString
$BSTR = [System.Runtime.InteropServices.Marshal]::SecureStringToBSTR($SecurePass)
$PlainPassword = [System.Runtime.InteropServices.Marshal]::PtrToStringAuto($BSTR)
[System.Runtime.InteropServices.Marshal]::ZeroFreeBSTR($BSTR)

# 2. Automatically generate the local .env file
$JdbcUrl = "jdbc:mysql://$($HostInput.Trim()):$PortInput/$DbName`?useSSL=true&sslMode=VERIFY_IDENTITY&enabledTLSProtocols=TLSv1.2,TLSv1.3&serverTimezone=UTC"

$EnvContent = @"
# Auto-generated by setup-cloud-db.ps1 (Strictly git-ignored)
CAMPUS_DB_URL=$JdbcUrl
CAMPUS_DB_USER=$($UserInput.Trim())
CAMPUS_DB_PASSWORD=$PlainPassword
"@

Set-Content -Path $EnvFilePath -Value $EnvContent -Encoding UTF8 -Force
Write-Host "`n[OK] .env file automatically created at: $EnvFilePath" -ForegroundColor Green

# 3. Check database schema and verify if data exists before importing
Write-Host "`nInspecting TiDB cluster schema..." -ForegroundColor Yellow
$ExistingTables = 0

if (Test-Path $MySqlExe) {
    # Check if database exists, create if not
    & $MySqlExe -h $HostInput.Trim() -P $PortInput -u $UserInput.Trim() -p"$PlainPassword" -e "CREATE DATABASE IF NOT EXISTS $DbName;" 2>$null
    
    # Check existing table count
    $tableCheck = & $MySqlExe -h $HostInput.Trim() -P $PortInput -u $UserInput.Trim() -p"$PlainPassword" -D $DbName -e "SELECT count(*) FROM information_schema.tables WHERE table_schema = '$DbName';" -s -N 2>$null
    if ($tableCheck -match "^\d+$") {
        $ExistingTables = [int]$tableCheck
    }
}

if ($ExistingTables -gt 0) {
    Write-Host "[NOTICE] Found $ExistingTables existing tables in TiDB database '$DbName'." -ForegroundColor Cyan
    Write-Host "[PRESERVED] Skipping data import to protect existing cloud records from being overwritten." -ForegroundColor Green
} else {
    Write-Host "[INFO] Cloud database '$DbName' is empty. Safely importing initial backup..." -ForegroundColor Yellow
    if (Test-Path $BackupFilePath) {
        if (Test-Path $MySqlExe) {
            Get-Content $BackupFilePath | & $MySqlExe -h $HostInput.Trim() -P $PortInput -u $UserInput.Trim() -p"$PlainPassword" -D $DbName
            Write-Host "[OK] Imported backup data (users, clubs, memberships, events, announcements)." -ForegroundColor Green
        } else {
            Write-Host "[WARN] mysql.exe not found at default path. You can import $BackupFilePath using TiDB Web SQL Editor." -ForegroundColor Yellow
        }
    } else {
        Write-Host "[WARN] Backup file not found at $BackupFilePath" -ForegroundColor Yellow
    }
}

# 4. Run the live Java DatabaseConnection test
Write-Host "`nRunning live Java DatabaseConnection test..." -ForegroundColor Yellow
if (-not (Test-Path $JarPath)) {
    Write-Host "Building application package..." -ForegroundColor Cyan
    mvn -f "$ProjectRoot\pom.xml" package -DskipTests -q
}

$testResult = java -cp $JarPath com.campusclub.util.DatabaseConnection
$testResult

if ($testResult -match "\[PASS\] Successfully connected") {
    Write-Host "`n============================================================" -ForegroundColor Green
    Write-Host "  VERIFICATION SUCCESSFUL: Live Cloud DB Connected!" -ForegroundColor Green
    Write-Host "============================================================" -ForegroundColor Green
    Write-Host "`nNext Step: Add these exact Environment Variables in your Render Dashboard:" -ForegroundColor Cyan
    Write-Host "CAMPUS_DB_URL      : $JdbcUrl"
    Write-Host "CAMPUS_DB_USER     : $($UserInput.Trim())"
    Write-Host "CAMPUS_DB_PASSWORD : [your password]"
} else {
    Write-Host "`n[FAIL] Live connection test did not pass. Please verify host, username, and password." -ForegroundColor Red
}
